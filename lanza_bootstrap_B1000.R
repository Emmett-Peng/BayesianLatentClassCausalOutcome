################################################################################
# lanza_bootstrap_B1000.R
#
# Re-runs ONLY the comparator (two-step inverse probability weighted latent class
# estimator of Lanza et al.) with a larger bootstrap (default B = 1000), on exactly
# the same simulated datasets as simulation_code.R. The Bayesian model is not fitted,
# so JAGS is not required. The comparator results in the paper come from this script.
#
# Why the datasets are identical to those of simulation_code.R:
#   * the scenario grid and the seed vector come from make_design();
#   * every dataset is generated by simulate_scenario_dataset(), which calls
#     set.seed(seed) internally, so a dataset depends on its own seed only.
#
# Usage
#   Rscript lanza_bootstrap_B1000.R                          # everything (long)
#   SCENARIOS=1 DATASETS=1-2 B_BOOT=20 Rscript lanza_bootstrap_B1000.R   # small test
#   sbatch run_lanza_bootstrap.sbatch                        # cluster: one array task per dataset
#   AGGREGATE_ONLY=1 Rscript lanza_bootstrap_B1000.R         # build the CSVs from the checkpoints
#
# Environment variables (all optional)
#   B_BOOT          bootstrap replicates                          (default: 1000)
#   SCENARIOS       scenario ids, e.g. "1,2,5-8"                  (default: all 16)
#   DATASETS        dataset ids, e.g. "1-25"                      (default: all 100)
#   OUT_SUBDIR      output directory                              (default: lanza_B<B>)
#   WORKERS         parallel workers          (default: SLURM_CPUS_PER_TASK, else 1)
#   FORCE           1 to recompute datasets that already have a checkpoint
#   AGGREGATE_ONLY  1 to skip fitting and only aggregate
#
# Slurm array mode: when SLURM_ARRAY_TASK_ID is set (and SCENARIOS/DATASETS are not),
# task t (1..1600) handles scenario ((t - 1) %/% 100) + 1, dataset ((t - 1) %% 100) + 1.
# Every task writes its own checkpoint, so tasks never write the same file; aggregate
# afterwards with AGGREGATE_ONLY=1.
#
# Outputs (in OUT_SUBDIR)
#   lanza_per_dataset_B<B>.csv   estimate, interval, truth and coverage per dataset and class
#   lanza_summary_B<B>.csv       MSE and coverage per scenario and class
################################################################################

source("simulation_functions.R")

## settings -------------------------------------------------------------------
B_BOOT         <- as.integer(Sys.getenv("B_BOOT", "1000"))
FORCE          <- Sys.getenv("FORCE", "0") == "1"
AGGREGATE_ONLY <- Sys.getenv("AGGREGATE_ONLY", "0") == "1"
OUT_SUBDIR     <- Sys.getenv("OUT_SUBDIR", paste0("lanza_B", B_BOOT))
WORKERS        <- get_workers()
K              <- 4L

design    <- make_design()
scenarios <- design$scenarios
seeds     <- design$seeds
D         <- SIM$D_per_scenario

scn_ids <- parse_ids(Sys.getenv("SCENARIOS", ""), scenarios$scenario_id)
ds_ids  <- parse_ids(Sys.getenv("DATASETS",  ""), seq_len(D))

array_id <- Sys.getenv("SLURM_ARRAY_TASK_ID", "")
if (nzchar(array_id) && !nzchar(Sys.getenv("SCENARIOS", "")) && !nzchar(Sys.getenv("DATASETS", ""))) {
  aid     <- as.integer(array_id)
  n_tasks <- nrow(scenarios) * D
  if (is.na(aid) || aid < 1L || aid > n_tasks) {
    stop("SLURM_ARRAY_TASK_ID must be in 1..", n_tasks, ", got: ", array_id)
  }
  scn_ids <- ((aid - 1L) %/% D) + 1L
  ds_ids  <- ((aid - 1L) %%  D) + 1L
  message("array task ", aid, " -> scenario ", scn_ids, ", dataset ", ds_ids)
}

dir.create(OUT_SUBDIR, showWarnings = FALSE, recursive = TRUE)
message("lanza_bootstrap_B1000.R: B_BOOT = ", B_BOOT, "; scenarios = ", paste(scn_ids, collapse = ","),
        "; datasets = ", length(ds_ids), " per scenario; workers = ", WORKERS)

## fitting -----------------------------------------------------------------------
ckpt_file <- function(r, d) file.path(OUT_SUBDIR, sprintf("rep_scn%02d_d%03d.rds", r, d))

# A dataset counts as done only if its checkpoint was produced at the same B,
# so that a directory left over from a run with another B is never mixed in.
ckpt_done_at_B <- function(r, d) {
  f <- ckpt_file(r, d)
  file.exists(f) && isTRUE(tryCatch(readRDS(f)$B_requested == B_BOOT, error = function(e) FALSE))
}

if (WORKERS > 1L) plan(multisession, workers = WORKERS) else plan(sequential)

for (r in if (AGGREGATE_ONLY) integer(0) else scn_ids) {
  scn  <- scenarios[r, ]
  base <- (r - 1L) * D
  message("[", format(Sys.time(), "%H:%M:%S"), "] scenario ", r, "/", nrow(scenarios), "  ", scenario_tag(scn))

  todo <- ds_ids
  if (!FORCE) {
    have <- vapply(ds_ids, function(d) ckpt_done_at_B(r, d), logical(1))
    todo <- ds_ids[!have]
    if (any(have)) message("  skipping ", sum(have), " dataset(s) already done at B = ", B_BOOT)
  }
  if (!length(todo)) next

  invisible(future_lapply(todo, function(d) {
    res <- tryCatch(run_comparator_one(scn, seed = seeds[base + d], B_boot = B_BOOT),
                    error = function(e) list(error = conditionMessage(e)))
    res$dataset <- d
    saveRDS(res, ckpt_file(r, d))
    NULL
  }, future.seed = TRUE))
}
plan(sequential)

## aggregation ------------------------------------------------------------------
# In array mode all tasks would write the same CSVs, so aggregate in a separate step.
if (nzchar(array_id) && !AGGREGATE_ONLY) {
  message("Array mode: skipping aggregation. Run with AGGREGATE_ONLY=1 when all tasks have finished.")
  quit(save = "no")
}

files <- list.files(OUT_SUBDIR, pattern = "^rep_scn[0-9]+_d[0-9]+[.]rds$", full.names = TRUE)
if (!length(files)) { message("No checkpoints to aggregate."); quit(save = "no") }
resL <- lapply(files, readRDS)

bad <- vapply(resL, function(x) !is.null(x$error), logical(1))
if (any(bad)) message("NOTE: ", sum(bad), " dataset(s) errored and are excluded.")
resL <- resL[!bad]

wrong_B <- vapply(resL, function(x) !isTRUE(x$B_requested == B_BOOT), logical(1))
if (any(wrong_B)) message("NOTE: ", sum(wrong_B), " checkpoint(s) were run at a different B and are excluded.")
resL <- resL[!wrong_B]
if (!length(resL)) { message("No checkpoints at B = ", B_BOOT, " to aggregate."); quit(save = "no") }

per_ds <- do.call(rbind, lapply(resL, function(rr) data.frame(
  Scenario_ID = rr$scenario_id, Scenario = rr$tag, n = rr$n,
  Conf = rr$confounding, Imb = rr$imbalance, Sep = rr$separation,
  dataset = rr$dataset, seed = rr$seed,
  B_requested = rr$B_requested, B_effective = rr$B_effective,
  Class = paste0("class", 1:K),
  mean = as.numeric(rr$base_mean),
  lwr  = as.numeric(rr$base_lwr),  upr = as.numeric(rr$base_upr),
  true = as.numeric(rr$base_true), cover = as.integer(rr$base_cover),
  stringsAsFactors = FALSE
)))
per_ds <- per_ds[order(per_ds$Scenario_ID, per_ds$dataset, per_ds$Class), ]
f1 <- file.path(OUT_SUBDIR, sprintf("lanza_per_dataset_B%d.csv", B_BOOT))
write.csv(per_ds, f1, row.names = FALSE)
message("Wrote: ", f1)

# Monte Carlo summary: same columns as the "Frequentist" rows of final_simulation_results.csv
summ <- do.call(rbind, lapply(split(per_ds, per_ds$Scenario_ID), function(dd) {
  do.call(rbind, lapply(split(dd, dd$Class), function(cc) data.frame(
    Scenario_ID = cc$Scenario_ID[1], n = cc$n[1], Conf = cc$Conf[1],
    Imb = cc$Imb[1], Sep = cc$Sep[1], Method = "Frequentist", Class = cc$Class[1],
    MSE      = mean((cc$mean - cc$true)^2, na.rm = TRUE),
    Coverage = mean(cc$cover, na.rm = TRUE),
    n_datasets = nrow(cc), B_requested = cc$B_requested[1],
    B_effective_mean = mean(cc$B_effective, na.rm = TRUE),
    stringsAsFactors = FALSE
  )))
}))
summ <- summ[order(summ$Scenario_ID, summ$Class), ]
rownames(summ) <- NULL
f2 <- file.path(OUT_SUBDIR, sprintf("lanza_summary_B%d.csv", B_BOOT))
write.csv(summ, f2, row.names = FALSE)
message("Wrote: ", f2)
message("Done.")
